import {cleanup,fireEvent,render,screen,waitFor} from "@testing-library/react";
import {afterEach,expect,it,vi} from "vitest";
import {CatalogImportForm} from "@/components/admin/catalog-import";
import {applyCatalogImport,previewCatalogImport,publishCatalogImport} from "@/app/actions/admin-products";
vi.mock("@/config/catalog-capabilities",()=>({catalogOnly:true}));
vi.mock("@/app/actions/admin-products",()=>({applyCatalogImport:vi.fn(),previewCatalogImport:vi.fn(),publishCatalogImport:vi.fn()}));
vi.mock("sonner",()=>({toast:{success:vi.fn(),error:vi.fn(),warning:vi.fn()}}));
afterEach(()=>{cleanup();sessionStorage.clear();vi.restoreAllMocks();});
it("requires an explicit publish after preparing, and binds reactivation/staging to the submitted file",async()=>{
 const summary={ok:true as const,productosNuevos:1,productosActualizar:0,variantesNuevas:1,variantesActualizar:0,fotosNuevas:0,categoriasNuevas:[],pisaStock:false};
 vi.mocked(previewCatalogImport).mockResolvedValue(summary);
 vi.mocked(applyCatalogImport).mockResolvedValue({...summary,variantesEscritas:0,fotosSubidas:0,fotosOmitidas:0,fotosFallidas:[],stagedReady:true,importId:"11111111-1111-4111-8111-111111111111"});
 vi.mocked(publishCatalogImport).mockResolvedValue({...summary,variantesEscritas:1,fotosSubidas:0,fotosOmitidas:0,fotosFallidas:[]});
 Object.defineProperty(File.prototype,"arrayBuffer",{configurable:true,value:async()=>new Uint8Array([1,2,3]).buffer});
 Object.defineProperty(crypto,"subtle",{configurable:true,value:{digest:async()=>new Uint8Array(32).buffer}});
 render(<CatalogImportForm/>);
 const fileInput=document.querySelector('input[type="file"]')!;
 fireEvent.change(fileInput,{target:{files:[new File(["fixture"],"catalogo.csv",{type:"text/csv"})]}});
 fireEvent.click(screen.getByLabelText(/Preparar y publicar/));
 fireEvent.click(screen.getByLabelText(/Reactivar productos/));
 fireEvent.click(screen.getByRole("button",{name:/Revisar/i}));
 await waitFor(()=>expect(previewCatalogImport).toHaveBeenCalledOnce());
 const confirm=await screen.findByRole("button",{name:/Confirmar/i});fireEvent.click(confirm);
 const publish=await screen.findByRole("button",{name:"Publicar planilla completa"});
 expect(publishCatalogImport).not.toHaveBeenCalled();
 const data=vi.mocked(applyCatalogImport).mock.calls[0]![0];
 expect(data.get("staged")).toBe("true");expect(data.get("republish")).toBe("true");
 fireEvent.click(publish);
 await waitFor(()=>expect(publishCatalogImport).toHaveBeenCalledWith({importId:"11111111-1111-4111-8111-111111111111"}));
 await waitFor(()=>expect(screen.queryByRole("button",{name:"Publicar planilla completa"})).toBeNull());
});
